/**
 * Темп стола: во сколько раз быстрее обычного проигрывается происходящее.
 *
 * Нужен ради одного случая — хода бота. Своим ходом игрок сам решает, когда
 * нажать, и растянутая вспышка ему не мешает; чужой ход он только смотрит, и
 * там каждая доля секунды складывается в ожидание.
 *
 * Множитель, а не набор готовых длительностей: длительности разбросаны по
 * эффектам и подобраны каждая под свой (взрыв базы длиннее щелчка счётчика).
 * Общий делитель сохраняет соотношения — ускоряется вся картина целиком, а не
 * распадается на быстрые и медленные куски.
 *
 * Значение глобальное и без реактивности: эффект живёт доли секунды и читает
 * темп РОВНО в момент запуска. Пакет событий приходит целиком, темп для него
 * выставляется перед запуском — внутри пакета он смениться не может.
 */

const MIN = 1
const MAX = 6

let rate = 1

/** Текущий множитель. */
export function tempo(): number {
  return rate
}

export function setTempo(next: number): void {
  rate = Number.isFinite(next) ? Math.min(MAX, Math.max(MIN, next)) : 1
}

/** Длительность (в чём угодно — секундах, миллисекундах) в текущем темпе. */
export function pace(duration: number): number {
  return duration / rate
}
