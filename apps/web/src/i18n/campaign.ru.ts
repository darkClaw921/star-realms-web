/** Цель миссии одной строкой — для стола, где место дорого. */
export function objectiveRu(o: Objective): string {
  switch (o.k) {
    case 'AUTHORITY': return 'Свести авторитет противника к нулю'
    case 'SURVIVE': return `Пережить ${o.turns} ходов`
    case 'DESTROY_BASES': return `Уничтожить баз: ${o.n}`
    case 'REACH_AUTHORITY': return `Довести свой авторитет до ${o.n}`
  }
}

/** Прогресс по цели, если его есть чем измерить. */
export function objectiveProgressRu(
  o: Objective, turn: number, destroyed: number, authority: number,
): string | null {
  switch (o.k) {
    case 'AUTHORITY': return null
    case 'SURVIVE': return `ход ${Math.min(turn, o.turns)} из ${o.turns}`
    case 'DESTROY_BASES': return `${Math.min(destroyed, o.n)} из ${o.n}`
    case 'REACH_AUTHORITY': return `${authority} из ${o.n}`
  }
}

