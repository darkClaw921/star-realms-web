/**
 * Rebuilds src/cards/artManifest.gen.ts from whatever is in public/cards/art/.
 *
 * The manifest is generated rather than committed. It has to exist for the app
 * to compile -- the renderer imports it -- but its contents describe files that
 * are NOT in the repository (the artwork is the publisher's), so committing it
 * would mean shipping a build that points at images nobody else has.
 *
 * So: the file is gitignored and this script guarantees it exists. No art
 * directory means an empty manifest, which is a perfectly good state -- every
 * card falls back to its procedural placeholder.
 *
 * Idempotent on purpose: identical output is not rewritten, so running it from
 * a pre-hook never touches the file's mtime and never invalidates a watcher.
 *
 * Usage: node scripts/art-manifest.mjs
 */
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ART_DIR = join(HERE, '..', 'public', 'cards', 'art')
const OUT = join(HERE, '..', 'src', 'cards', 'artManifest.gen.ts')

/** Must match the sizes fetch-cards.ts writes. */
const SIZES = [320, 640]

/**
 * Reads dimensions out of a WebP header.
 *
 * Only enough of the format to get width and height, because pulling in an
 * image library for a build pre-hook would be a heavy dependency for six bytes.
 * Handles the two encodings fetch-cards produces: VP8L (lossless) and VP8X
 * (extended). Anything unrecognised is skipped rather than guessed at.
 */
function webpSize(buf) {
  if (buf.length < 30) return null
  if (buf.toString('ascii', 0, 4) !== 'RIFF' || buf.toString('ascii', 8, 12) !== 'WEBP') return null
  const chunk = buf.toString('ascii', 12, 16)

  if (chunk === 'VP8X') {
    return {
      w: 1 + buf.readUIntLE(24, 3),
      h: 1 + buf.readUIntLE(27, 3),
    }
  }
  if (chunk === 'VP8L') {
    const b = buf.readUInt32LE(21)
    return {
      w: 1 + (b & 0x3fff),
      h: 1 + ((b >> 14) & 0x3fff),
    }
  }
  if (chunk === 'VP8 ') {
    return {
      w: buf.readUInt16LE(26) & 0x3fff,
      h: buf.readUInt16LE(28) & 0x3fff,
    }
  }
  return null
}

async function main() {
  /** @type {Record<string, {w: number, h: number, orientation: 'portrait'|'landscape'}>} */
  const manifest = {}

  let files = []
  try {
    files = await readdir(ART_DIR)
  } catch {
    // No art downloaded. An empty manifest is the correct answer, not an error.
  }

  const smallest = SIZES[0]
  for (const f of files.sort()) {
    const m = /^(.+)-(\d+)\.webp$/.exec(f)
    if (!m || Number(m[2]) !== smallest) continue
    const id = m[1]
    const size = webpSize(await readFile(join(ART_DIR, f)))
    if (!size) continue
    manifest[id] = {
      w: size.w,
      h: size.h,
      orientation: size.w >= size.h ? 'landscape' : 'portrait',
    }
  }

  const body = `// GENERATED by scripts/art-manifest.mjs -- do not edit, do not commit.
//
// This file is gitignored: it describes files in public/cards/art/, which are
// the publisher's artwork and are not in the repository. It is rebuilt from
// whatever art is present before dev, build and typecheck, so a fresh clone
// gets a valid empty manifest and compiles.
//
// A missing card is simply an absent key: the renderer then falls back to its
// procedural placeholder, with no runtime 404 and no broken-image glyph.
export interface ArtEntry {
  /** Dimensions of the CROPPED illustration, not the source scan. */
  readonly w: number
  readonly h: number
  readonly orientation: 'portrait' | 'landscape'
}

export const ART_SIZES = [${SIZES.join(', ')}] as const

export const ART_MANIFEST: Readonly<Record<string, ArtEntry>> = ${JSON.stringify(manifest, null, 2)}

export function artUrl(cardId: string, size: (typeof ART_SIZES)[number] = 320): string | null {
  return ART_MANIFEST[cardId] ? \`/cards/art/\${cardId}-\${size}.webp\` : null
}
`

  let current = null
  try { current = await readFile(OUT, 'utf8') } catch { /* not there yet */ }
  if (current === body) return

  await mkdir(dirname(OUT), { recursive: true })
  await writeFile(OUT, body, 'utf8')
  const n = Object.keys(manifest).length
  console.log(`art manifest: ${n} card${n === 1 ? '' : 's'}`)
}

await main()
